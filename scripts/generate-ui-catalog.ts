import fs from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const COMPONENTS_DIR = path.join(ROOT, "src", "components");
const OUTPUT_PATH = path.join(
	ROOT,
	".agents",
	"skills",
	"frontend-ui",
	"references",
	"components.generated.md",
);

interface CatalogEntry {
	relPath: string;
	importPath: string;
	exports: string[];
}

function toPosix(filePath: string): string {
	return filePath.split(path.sep).join("/");
}

function isIgnoredFile(fileName: string): boolean {
	return (
		fileName === "index.ts" ||
		fileName === "index.tsx" ||
		/\.(?:test|stories)\.[^.]+$/.test(fileName)
	);
}

function extractExports(source: string): string[] {
	const names = new Set<string>();
	const declRe =
		/\bexport\s+(?:async\s+)?(?:function|const|let|class|type|interface|enum)\s+([A-Za-z0-9_]+)/g;
	for (const match of source.matchAll(declRe)) {
		names.add(match[1]);
	}

	const listRe = /\bexport\s+(?:type\s+)?\{([^}]+)\}/g;
	for (const match of source.matchAll(listRe)) {
		for (const rawItem of match[1].split(",")) {
			const cleaned = rawItem.replace(/^\s*type\s+/, "").trim();
			if (!cleaned) {
				continue;
			}
			const aliasSplit = cleaned.split(/\s+as\s+/);
			const exportedName = (aliasSplit[1] ?? aliasSplit[0]).trim();
			if (exportedName) {
				names.add(exportedName);
			}
		}
	}

	return [...names].sort();
}

function buildEntry(absPath: string): CatalogEntry {
	const relPath = toPosix(path.relative(ROOT, absPath));
	const importPath = relPath
		.replace(/^src\//, "@/")
		.replace(/\.(?:tsx|ts)$/, "");
	const source = fs.readFileSync(absPath, "utf8");
	return {
		relPath,
		importPath,
		exports: extractExports(source),
	};
}

function collectLayerFiles(dir: string, recursive: boolean): CatalogEntry[] {
	if (!fs.existsSync(dir)) {
		return [];
	}
	const files: string[] = [];
	for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
		const fullPath = path.join(dir, entry.name);
		if (entry.isDirectory()) {
			if (recursive) {
				for (const subEntry of collectLayerFiles(fullPath, true)) {
					files.push(path.join(ROOT, subEntry.relPath));
				}
			}
			continue;
		}
		if (
			entry.isFile() &&
			/\.(?:tsx|ts)$/.test(entry.name) &&
			!isIgnoredFile(entry.name)
		) {
			if (!recursive && !entry.name.endsWith(".tsx")) {
				continue;
			}
			files.push(fullPath);
		}
	}
	return files.sort().map(buildEntry);
}

function wrapBullet(
	bulletPrefix: string,
	continuationPrefix: string,
	text: string,
): string[] {
	const words = text.split(" ");
	const lines: string[] = [];
	let current = bulletPrefix;

	for (const word of words) {
		const candidate =
			current === bulletPrefix ? `${current}${word}` : `${current} ${word}`;
		if (candidate.length > 100 && current !== bulletPrefix) {
			lines.push(current);
			current = `${continuationPrefix}${word}`;
		} else {
			current = candidate;
		}
	}
	lines.push(current);
	return lines;
}

function formatSection(title: string, entries: CatalogEntry[]): string[] {
	const lines: string[] = [`## ${title}`, ""];
	if (entries.length === 0) {
		lines.push("- _(none yet)_", "");
		return lines;
	}
	for (const entry of entries) {
		const exportsLabel =
			entry.exports.length > 0 ? entry.exports.join(", ") : "no named exports";
		const entryText = `\`${entry.relPath}\` (\`${entry.importPath}\`): ${exportsLabel}`;
		lines.push(...wrapBullet("- ", "  ", entryText));
	}
	lines.push("");
	return lines;
}

function main(): void {
	const uiEntries = collectLayerFiles(path.join(COMPONENTS_DIR, "ui"), true);
	const patternEntries = collectLayerFiles(
		path.join(COMPONENTS_DIR, "patterns"),
		true,
	);
	const productEntries = collectLayerFiles(COMPONENTS_DIR, false);

	const output = [
		"# Frontend UI Component Catalog",
		"",
		"Generated by `bun scripts/generate-ui-catalog.ts`. Do not edit manually.",
		"",
		...formatSection("Patterns (`src/components/patterns/`)", patternEntries),
		...formatSection(
			"Product Components (`src/components/*.tsx`)",
			productEntries,
		),
		...formatSection("shadcn/ui Primitives (`src/components/ui/`)", uiEntries),
	].join("\n");

	fs.mkdirSync(path.dirname(OUTPUT_PATH), { recursive: true });
	fs.writeFileSync(OUTPUT_PATH, output, "utf8");
	console.log(
		`Generated ${toPosix(path.relative(ROOT, OUTPUT_PATH))} (${patternEntries.length} patterns, ${productEntries.length} product components, ${uiEntries.length} primitives)`,
	);
}

main();
